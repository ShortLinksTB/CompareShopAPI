using Microsoft.EntityFrameworkCore;
using CompareShopAPI.Domain.Catalog;
using CompareShopAPI.Domain.UserCommerce;
using CompareShopAPI.Domain.Admin;
using CompareShopAPI.Domain.Articles;
namespace CompareShopAPI.Infrastructure.Persistence;
public sealed class CompareShopDbContext(DbContextOptions<CompareShopDbContext> options) : DbContext(options)
{
    public DbSet<Category> Categories => Set<Category>();
    public DbSet<Product> Products => Set<Product>();
    public DbSet<PartnerShop> PartnerShops => Set<PartnerShop>();
    public DbSet<ProductOffer> ProductOffers => Set<ProductOffer>();
    public DbSet<SpecificationGroup> SpecificationGroups => Set<SpecificationGroup>();
    public DbSet<SpecificationItem> SpecificationItems => Set<SpecificationItem>();
    public DbSet<AffiliateLink> AffiliateLinks => Set<AffiliateLink>();
    public DbSet<AffiliateClick> AffiliateClicks => Set<AffiliateClick>();
    public DbSet<User> Users => Set<User>();
    public DbSet<WishlistItem> WishlistItems => Set<WishlistItem>();
    public DbSet<PriceAlert> PriceAlerts => Set<PriceAlert>();
    public DbSet<PriceHistoryPoint> PriceHistoryPoints => Set<PriceHistoryPoint>();
    public DbSet<AdminRole> AdminRoles => Set<AdminRole>();
    public DbSet<AdminPermission> AdminPermissions => Set<AdminPermission>();
    public DbSet<AdminRolePermission> AdminRolePermissions => Set<AdminRolePermission>();
    public DbSet<AdminUserRole> AdminUserRoles => Set<AdminUserRole>();
    public DbSet<AdminAuditLog> AdminAuditLogs => Set<AdminAuditLog>();
    public DbSet<AdminFeatureFlag> AdminFeatureFlags => Set<AdminFeatureFlag>();
    public DbSet<AdminSetting> AdminSettings => Set<AdminSetting>();
    public DbSet<ProductMatching> ProductMatchings => Set<ProductMatching>();
    public DbSet<Article> Articles => Set<Article>();
    public DbSet<ArticleRelatedProduct> ArticleRelatedProducts => Set<ArticleRelatedProduct>();
    protected override void OnModelCreating(ModelBuilder model)
    {
        model.Entity<Category>().HasKey(x => x.Id); model.Entity<Category>().HasIndex(x => x.Slug).IsUnique(); model.Entity<Category>().HasIndex(x => x.IsActive);
        model.Entity<Category>().Property(x => x.Slug).HasMaxLength(160); model.Entity<Category>().Property(x => x.Name).HasMaxLength(200);
        model.Entity<PartnerShop>().HasKey(x => x.Id); model.Entity<PartnerShop>().HasIndex(x => x.Slug).IsUnique(); model.Entity<PartnerShop>().HasIndex(x => x.IsActive);
        model.Entity<PartnerShop>().Property(x => x.Slug).HasMaxLength(160); model.Entity<PartnerShop>().Property(x => x.Name).HasMaxLength(200);
        model.Entity<Product>().HasKey(x => x.Id); model.Entity<Product>().HasIndex(x => x.Slug).IsUnique();
        model.Entity<Product>().HasIndex(x => new { x.IsActive, x.CategoryId }); model.Entity<Product>().Property(x => x.Slug).HasMaxLength(200);
        model.Entity<Product>().Property(x => x.Name).HasMaxLength(300); model.Entity<Product>().Property(x => x.Brand).HasMaxLength(200);
        model.Entity<Product>().HasOne(x => x.Category).WithMany().HasForeignKey(x => x.CategoryId).OnDelete(DeleteBehavior.Restrict);
        model.Entity<ProductOffer>().HasKey(x => x.Id); model.Entity<ProductOffer>().HasIndex(x => new { x.ProductId, x.IsActive, x.IsOutlier });
        model.Entity<ProductOffer>().HasIndex(x => new { x.PartnerShopId, x.ProductId }); model.Entity<ProductOffer>().HasIndex(x => new { x.PriceVnd, x.UpdatedAtUtc });
        model.Entity<ProductOffer>().HasOne(x => x.Product).WithMany(x => x.Offers).HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<ProductOffer>().HasOne(x => x.PartnerShop).WithMany().HasForeignKey(x => x.PartnerShopId).OnDelete(DeleteBehavior.Restrict);
        model.Entity<SpecificationGroup>().HasOne(x => x.Product).WithMany(x => x.SpecificationGroups).HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<SpecificationItem>().HasOne(x => x.Group).WithMany(x => x.Items).HasForeignKey(x => x.SpecificationGroupId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<SpecificationGroup>().Property(x => x.Name).HasMaxLength(200);
        model.Entity<SpecificationItem>().Property(x => x.Name).HasMaxLength(200); model.Entity<SpecificationItem>().Property(x => x.Value).HasMaxLength(1000);
        model.Entity<AffiliateLink>().HasKey(x => x.Id);
        model.Entity<AffiliateLink>().HasIndex(x => x.ProductOfferId).IsUnique();
        model.Entity<AffiliateLink>().Property(x => x.DestinationUrl).HasMaxLength(2048);
        model.Entity<AffiliateLink>().Property(x => x.Revenue).HasColumnType("decimal(18,2)");
        model.Entity<AffiliateLink>().HasOne(x => x.ProductOffer).WithOne().HasForeignKey<AffiliateLink>(x => x.ProductOfferId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<AffiliateClick>().HasKey(x => x.Id);
        model.Entity<AffiliateClick>().HasIndex(x => new { x.AffiliateLinkId, x.ClickedAtUtc });
        model.Entity<AffiliateClick>().Property(x => x.ClientIpDigest).HasMaxLength(64);
        model.Entity<AffiliateClick>().HasOne(x => x.AffiliateLink).WithMany().HasForeignKey(x => x.AffiliateLinkId).OnDelete(DeleteBehavior.Cascade);

        model.Entity<User>().HasKey(x => x.Id);
        model.Entity<User>().HasIndex(x => x.KeycloakSubject).IsUnique();
        model.Entity<User>().Property(x => x.KeycloakSubject).HasMaxLength(200).IsRequired();
        model.Entity<User>().Property(x => x.CreatedAtUtc).IsRequired();
        model.Entity<WishlistItem>().HasKey(x => x.Id);
        model.Entity<WishlistItem>().HasIndex(x => new { x.UserId, x.ProductId }).IsUnique();
        model.Entity<WishlistItem>().HasIndex(x => new { x.UserId, x.CreatedAtUtc });
        model.Entity<WishlistItem>().HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<WishlistItem>().HasOne(x => x.Product).WithMany().HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<PriceAlert>().HasKey(x => x.Id);
        model.Entity<PriceAlert>().ToTable(table => table.HasCheckConstraint("CK_PriceAlerts_TargetPrice_Positive", "[TargetPrice] > 0"));
        model.Entity<PriceAlert>().HasIndex(x => new { x.UserId, x.IsActive, x.ProductId });
        model.Entity<PriceAlert>().HasIndex(x => new { x.ProductId, x.IsActive });
        model.Entity<PriceAlert>().HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<PriceAlert>().HasOne(x => x.Product).WithMany().HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<PriceHistoryPoint>().HasKey(x => x.Id);
        model.Entity<PriceHistoryPoint>().Property(x => x.DateUtc).HasColumnType("datetime2");
        model.Entity<PriceHistoryPoint>().HasIndex(x => new { x.ProductId, x.DateUtc });
        model.Entity<PriceHistoryPoint>().HasOne(x => x.Product).WithMany().HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Restrict);
        model.Entity<PriceHistoryPoint>().HasOne(x => x.PartnerShop).WithMany().HasForeignKey(x => x.PartnerShopId).OnDelete(DeleteBehavior.SetNull);
        model.Entity<Product>().Property(x => x.SeoTitle).HasMaxLength(200);
        model.Entity<Product>().Property(x => x.SeoDescription).HasMaxLength(500);
        model.Entity<AdminRole>().HasKey(x => x.Id); model.Entity<AdminRole>().HasIndex(x => x.Name).IsUnique(); model.Entity<AdminRole>().Property(x => x.Name).HasMaxLength(80).IsRequired();
        model.Entity<AdminPermission>().HasKey(x => x.Id); model.Entity<AdminPermission>().HasIndex(x => x.Key).IsUnique(); model.Entity<AdminPermission>().Property(x => x.Key).HasMaxLength(100).IsRequired();
        model.Entity<AdminRolePermission>().HasKey(x => new { x.RoleId, x.PermissionId });
        model.Entity<AdminRolePermission>().HasOne<AdminRole>().WithMany().HasForeignKey(x => x.RoleId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<AdminRolePermission>().HasOne<AdminPermission>().WithMany().HasForeignKey(x => x.PermissionId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<AdminUserRole>().HasKey(x => new { x.UserId, x.RoleId });
        model.Entity<AdminUserRole>().HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<AdminUserRole>().HasOne<AdminRole>().WithMany().HasForeignKey(x => x.RoleId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<AdminAuditLog>().HasKey(x => x.Id); model.Entity<AdminAuditLog>().Property(x => x.ActorSubject).HasMaxLength(200).IsRequired(); model.Entity<AdminAuditLog>().Property(x => x.Action).HasMaxLength(80).IsRequired(); model.Entity<AdminAuditLog>().Property(x => x.ResourceType).HasMaxLength(100).IsRequired(); model.Entity<AdminAuditLog>().Property(x => x.ResourceId).HasMaxLength(200); model.Entity<AdminAuditLog>().HasIndex(x => x.CreatedAtUtc);
        model.Entity<AdminFeatureFlag>().HasKey(x => x.Id); model.Entity<AdminFeatureFlag>().HasIndex(x => x.Key).IsUnique(); model.Entity<AdminFeatureFlag>().Property(x => x.Key).HasMaxLength(120).IsRequired(); model.Entity<AdminFeatureFlag>().Property(x => x.Description).HasMaxLength(500);
        model.Entity<AdminSetting>().HasKey(x => x.Id); model.Entity<AdminSetting>().HasIndex(x => x.Key).IsUnique(); model.Entity<AdminSetting>().Property(x => x.Key).HasMaxLength(120).IsRequired(); model.Entity<AdminSetting>().Property(x => x.Value).HasMaxLength(500).IsRequired();
        model.Entity<ProductMatching>().HasKey(x => x.Id); model.Entity<ProductMatching>().Property(x => x.Name).HasMaxLength(300).IsRequired(); model.Entity<ProductMatching>().Property(x => x.Brand).HasMaxLength(200); model.Entity<ProductMatching>().HasIndex(x => new { x.IsApproved, x.CreatedAtUtc });
        model.Entity<ProductMatching>().HasOne<Product>().WithMany().HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.SetNull);

        model.Entity<Article>().HasKey(x => x.Id);
        model.Entity<Article>().Property(x => x.Slug).HasMaxLength(200).IsRequired();
        model.Entity<Article>().HasIndex(x => x.Slug).IsUnique();
        model.Entity<Article>().HasIndex(x => new { x.Status, x.ScheduledAtUtc });
        model.Entity<Article>().Property(x => x.Title).HasMaxLength(300).IsRequired();
        model.Entity<Article>().Property(x => x.Excerpt).HasMaxLength(1000).IsRequired();
        model.Entity<Article>().Property(x => x.CoverImageUrl).HasMaxLength(2048);
        model.Entity<Article>().Property(x => x.AuthorSubject).HasMaxLength(200).IsRequired();
        model.Entity<Article>().Property(x => x.AuthorName).HasMaxLength(200).IsRequired();
        model.Entity<Article>().Property(x => x.AuthorAvatarUrl).HasMaxLength(2048);
        model.Entity<Article>().Property(x => x.Content).IsRequired();
        model.Entity<Article>().Property(x => x.Status).HasConversion<string>().HasMaxLength(20).IsRequired();
        model.Entity<Article>().OwnsOne(x => x.Seo, seo =>
        {
            seo.Property(x => x.Title).HasColumnName("SeoTitle").HasMaxLength(200);
            seo.Property(x => x.Description).HasColumnName("SeoDescription").HasMaxLength(500);
            seo.Property(x => x.CanonicalUrl).HasColumnName("SeoCanonicalUrl").HasMaxLength(2048);
            seo.Property(x => x.OgImage).HasColumnName("SeoOgImage").HasMaxLength(2048);
            seo.Property(x => x.Index).HasColumnName("SeoIndex").IsRequired();
        });
        model.Entity<Article>().HasMany(x => x.RelatedProducts).WithOne().HasForeignKey(x => x.ArticleId).OnDelete(DeleteBehavior.Cascade);
        model.Entity<ArticleRelatedProduct>().HasKey(x => new { x.ArticleId, x.ProductId });
        model.Entity<ArticleRelatedProduct>().HasOne<Product>().WithMany().HasForeignKey(x => x.ProductId).OnDelete(DeleteBehavior.Restrict);
    }
}
